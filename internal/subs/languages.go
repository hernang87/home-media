// byName maps a lower-cased full language name to its 2-letter code. Built the
// same way as the JS loop: codes in alphabetical order, later ones overwrite.
var byName = buildByName()

func buildByName() map[string]string {
	codes := make([]string, 0, 256)
	for c := range languageNames {
		if len(c) == 2 {
			codes = append(codes, c)
		}
	}
	sort.Strings(codes)
	m := make(map[string]string, len(codes))
	for _, c := range codes {
		m[strings.ToLower(languageNames[c])] = c
	}
	return m
}

